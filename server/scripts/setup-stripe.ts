/**
 * Creates KrakenInterview Stripe products/prices and writes server/.env.
 * Requires STRIPE_SECRET_KEY (test or live).
 *
 * Usage: npm run setup:stripe --prefix server
 */
import 'dotenv/config'
import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import Stripe from 'stripe'

const __dirname = dirname(fileURLToPath(import.meta.url))
const envPath = join(__dirname, '..', '.env')

const PRODUCT_NAME = 'KrakenInterview Pro'
const PRODUCT_DESCRIPTION =
  'AI interview copilot — coding, system design, behavioral rounds with JD context and Mermaid diagrams.'

const PRICES = [
  { envKey: 'STRIPE_PRICE_WEEKLY', nickname: 'Pro Weekly', amount: 2400, interval: 'week' as const },
  { envKey: 'STRIPE_PRICE_MONTHLY', nickname: 'Pro Monthly', amount: 5400, interval: 'month' as const },
  { envKey: 'STRIPE_PRICE_LIFETIME', nickname: 'Lifetime', amount: 68400, oneTime: true }
] as const

function stripeKeyFromCliConfig(): string | undefined {
  const configPath = join(homedir(), '.config', 'stripe', 'config.toml')
  if (!existsSync(configPath)) return undefined
  const match = readFileSync(configPath, 'utf8').match(/test_mode_api_key\s*=\s*"([^"]+)"/)
  return match?.[1]
}

function loadExistingEnv(): Record<string, string> {
  if (!existsSync(envPath)) return {}
  const out: Record<string, string> = {}
  for (const line of readFileSync(envPath, 'utf8').split('\n')) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const eq = trimmed.indexOf('=')
    if (eq === -1) continue
    out[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim()
  }
  return out
}

function writeEnv(values: Record<string, string>): void {
  const lines = [
    '# Stripe API (server) — generated by setup-stripe.ts',
    `STRIPE_SECRET_KEY=${values.STRIPE_SECRET_KEY ?? ''}`,
    `STRIPE_WEBHOOK_SECRET=${values.STRIPE_WEBHOOK_SECRET ?? ''}`,
    '',
    '# Price IDs (KrakenInterview plans)',
    `STRIPE_PRICE_WEEKLY=${values.STRIPE_PRICE_WEEKLY ?? ''}`,
    `STRIPE_PRICE_MONTHLY=${values.STRIPE_PRICE_MONTHLY ?? ''}`,
    `STRIPE_PRICE_LIFETIME=${values.STRIPE_PRICE_LIFETIME ?? ''}`,
    '',
    `PORT=${values.PORT ?? '4242'}`,
    `WEBSITE_ORIGIN=${values.WEBSITE_ORIGIN ?? 'http://localhost:5174'}`,
    ''
  ]
  writeFileSync(envPath, lines.join('\n'), 'utf8')
}

async function findOrCreateProduct(stripe: Stripe): Promise<string> {
  const existing = await stripe.products.search({
    query: `name:'${PRODUCT_NAME}' AND active:'true'`,
    limit: 1
  })
  if (existing.data[0]) {
    console.info(`Using existing product: ${existing.data[0].id}`)
    return existing.data[0].id
  }

  const product = await stripe.products.create({
    name: PRODUCT_NAME,
    description: PRODUCT_DESCRIPTION,
    metadata: { app: 'kraken-interview' }
  })
  console.info(`Created product: ${product.id}`)
  return product.id
}

async function findOrCreatePrice(
  stripe: Stripe,
  productId: string,
  spec: (typeof PRICES)[number]
): Promise<string> {
  const prices = await stripe.prices.list({ product: productId, active: true, limit: 100 })
  const match = prices.data.find((p) => {
    if (p.unit_amount !== spec.amount) return false
    if ('oneTime' in spec && spec.oneTime) return p.type === 'one_time'
    if ('interval' in spec) {
      return p.type === 'recurring' && p.recurring?.interval === spec.interval
    }
    return false
  })
  if (match) {
    console.info(`Using existing price (${spec.nickname}): ${match.id}`)
    return match.id
  }

  const price = await stripe.prices.create({
    product: productId,
    currency: 'usd',
    unit_amount: spec.amount,
    nickname: spec.nickname,
    ...('oneTime' in spec && spec.oneTime
      ? {}
      : { recurring: { interval: (spec as { interval: 'week' | 'month' }).interval } }),
    metadata: { plan: spec.envKey.replace('STRIPE_PRICE_', '').toLowerCase() }
  })
  console.info(`Created price (${spec.nickname}): ${price.id}`)
  return price.id
}

async function main(): Promise<void> {
  const secretKey = process.env.STRIPE_SECRET_KEY?.trim() || stripeKeyFromCliConfig()
  if (!secretKey) {
    console.error('No Stripe key found. Either:')
    console.error('  1. Run `stripe login`, then re-run this script')
    console.error('  2. Set STRIPE_SECRET_KEY=sk_test_... and re-run')
    process.exit(1)
  }

  const stripe = new Stripe(secretKey)
  const existing = loadExistingEnv()
  const productId = await findOrCreateProduct(stripe)

  const priceIds: Record<string, string> = {}
  for (const spec of PRICES) {
    priceIds[spec.envKey] = await findOrCreatePrice(stripe, productId, spec)
  }

  writeEnv({
    STRIPE_SECRET_KEY: secretKey,
    STRIPE_WEBHOOK_SECRET: existing.STRIPE_WEBHOOK_SECRET ?? process.env.STRIPE_WEBHOOK_SECRET ?? '',
    STRIPE_PRICE_WEEKLY: priceIds.STRIPE_PRICE_WEEKLY,
    STRIPE_PRICE_MONTHLY: priceIds.STRIPE_PRICE_MONTHLY,
    STRIPE_PRICE_LIFETIME: priceIds.STRIPE_PRICE_LIFETIME,
    PORT: existing.PORT ?? process.env.PORT ?? '4242',
    WEBSITE_ORIGIN: existing.WEBSITE_ORIGIN ?? process.env.WEBSITE_ORIGIN ?? 'http://localhost:5174'
  })

  console.info(`\nWrote ${envPath}`)
  console.info('Next: forward webhooks for local dev:')
  console.info('  stripe listen --forward-to localhost:4242/api/webhook')
  console.info('Then paste the whsec_... value into STRIPE_WEBHOOK_SECRET in server/.env')
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error)
  process.exit(1)
})
